import type { SimulatorState } from "@/lib/simulator/types";

// 結果⑨「就農ロードマップ」フェーズ別タイムライン
// 出典：agri-simulator-v4.html（旧版）buildResult()内のロードマップ構築ロジック（545〜627行目）を移植。
// 旧版は回答内容（研修要否・年齢・自己資金・移住元）に応じて3〜5ステップを動的に組み立てていたが、
// Next版では固定4フェーズの静的配列になっていたため、この関数で旧版のロジック・文言を復元する。

export type RoadmapStep = {
  icon: string;
  phase: string;
  title: string;
  description: string;
  details: string[];
  warn?: string;
};

export function buildRoadmap(s: SimulatorState): RoadmapStep[] {
  const steps: RoadmapStep[] = [];

  // 50歳以上は就農準備資金（研修中の生活支援）の対象外
  const trainOk = s.age !== "50p";
  // 農業法人に就職する人は、認定新規就農者の手続きを案内しない（経営開始資金は独立・自営就農が前提。2026年11月1日）
  const isHire = s.type === "hire";
  // 農業バイト経験あり／研修経験ありは「経験者」として研修フェーズをスキップ
  const hasExp = s.exp === "part" || s.exp === "train";
  // ふくしま移住支援金は東京23区在住・東京圏から23区へ通勤などが対象（「その他の都市部」は対象外）。
  // 出典：福島県「ふくしま移住支援金給付事業について」（2026年7月27日更新）。calculations.ts と同じ条件。
  const fromTokyo = s.loc === "tokyo";

  // お試し就農生の応募資格は「研修後に農業法人等で雇用就農を目指す方」なので、
  // Q6で「雇用されて始める（hire）」「まだわからない（idk）」を選んだ未経験者にだけ出す。
  // 独立（self）・継承（inherit）を選んだ人は、就農支援センターへの相談から始める。
  const showTrainee = !hasExp && (s.type === "hire" || s.type === "idk");

  if (showTrainee) {
    // 「お試し就農生」の内容の出典：ふくのう「お試し就農生募集」https://start-fukuagri.jp/trainee/ （2026年10月27日に確認）。
    // 1〜3日の無料体験ではなく、時給制の研修生として県内の農業法人等で働き、研修後の雇用就農を目指す仕組み。
    steps.push({
      icon: "🔍",
      phase: "まず最初に",
      title: "ふくのうの「お試し就農生」の募集を確かめる",
      description:
        "県内の農業法人などで、時給制の研修生として働きながら農業の基礎を学ぶ仕組みです。研修のあとに農業法人などで雇用就農を目指す人が対象です。就農準備資金を受けて研修機関で学ぶ研修とは、別の仕組みです。",
      details: [
        "📞 募集の掲載：福島県の就農サイト「ふくのう」（申し込み・問い合わせは募集ページから）",
        "🌐 start-fukuagri.jp/trainee/ で募集内容を確認",
        "📅 募集の時期・人数は年度ごとに変わります",
        "💰 時給制（交通費・住居手当は上限あり）。金額は募集ページで確認",
        "📋 研修期間中は運営会社の派遣社員として、受入先の農業法人などで働きます",
        "⚠️ 研修後に受入先で直接雇用されることは保障されていません",
      ],
    });
  } else {
    steps.push({
      icon: "📋",
      phase: "まず最初に",
      title: "就農支援センターへの相談を申し込む",
      description:
        "就農の手順や補助金、研修先の探し方、認定新規就農者の認定に向けた計画づくりなどを相談できます。",
      details: [
        "📞 相談先：福島県農業経営・就農支援センター（申し込みは「ふくのう」から）",
        "🌐 start-fukuagri.jp/syuno/ から申し込み（オンライン相談も選べます）",
        "📋 青年等就農計画（認定新規就農者になるための計画）の作成サポートあり",
      ],
    });
  }

  if (trainOk && !hasExp) {
    steps.push({
      icon: "📚",
      phase: "研修フェーズ（年間165万円を交付を受けながら）",
      title: "農業研修機関に登録して研修を受ける",
      description:
        "就農準備資金（年間165万円）を受け取りながら農業を学べます。研修期間中に農地・農機・販路の目処を立てます。",
      details: [
        "💰 就農準備資金：年間165万円（月13.75万円。令和8年度からの新規交付分）を最長2年間受給",
        "📅 研修期間：年間1,200時間以上が条件",
        "🏛️ 研修先の探し方：就農支援センター（申し込みは「ふくのう」から）に相談できます",
        "📋 start-fukuagri.jp/procedure/ で就農ステップ全体を確認",
      ],
      warn: "就農準備資金は最長2年間です。研修先や時期は、早めに就農支援センターに相談しておくと選びやすくなります。",
    });
  }

  if (s.cap === "u100" || s.cap === "100to300") {
    steps.push({
      icon: "🏦",
      phase: "資金調達",
      title: "日本政策金融公庫に農業融資の相談をする",
      description:
        "新しく農業を始める人向けの融資（認定新規就農者が使える青年等就農資金など）があります。使えるかどうかは個別の審査です。まず相談だけでもOKです。",
      details: [
        "🏦 相談先：日本政策金融公庫（農業融資窓口）",
        "📋 融資の申し込みには、経営の計画が必要です",
        "✅ 「相談だけ」でも対応してもらえます。まず電話予約から",
      ],
    });
  }

  const certStep: RoadmapStep = {
    icon: "📋",
    phase: "就農開始",
    title: "「認定新規就農者」の認定を取得する",
    description: trainOk
      ? "青年等就農計画を市町村に出して認定を受けます。経営開始資金（年間165万円×最長3年）など、認定が条件の支援があります（就農準備資金や移住支援金のように、認定がなくても使えるものもあります）。"
      : "青年等就農計画を市町村に出して認定を受けます。50歳以上は使える支援が限られるので、窓口で確かめてください。",
    details: [
      "🏛️ 申請先：市町村（青年等就農計画を提出）",
      ...(trainOk
        ? [
            "💰 認定後：経営開始資金 年間165万円×最長3年間（令和8年度からの新規交付分）",
            "💰 認定後：機械・施設には経営発展支援事業（経営開始資金と一緒に使うなら通常枠・国費上限250万円）",
            "💰 経営開始資金を受けない場合は、地域計画早期実現支援枠（国費上限600万円、県と合わせて最大900万円）も選べる",
          ]
        : ["💰 50歳以上は経営開始資金と経営発展支援事業の対象外です。機械・施設は新規就農者チャレンジ事業（独立・自営就農時65歳未満）や市町村の制度を確かめてください"]),
      // 確定申告・青色申告の案内：農林水産省 新規就農者育成総合対策のページ（https://www.maff.go.jp/j/new_farmer/n_syunou/roudou.html ）の「受給者の確定申告について」「青色申告を始めましょう」
      "📒 交付を受けたら確定申告が必要です。青色申告の始め方は農林水産省の新規就農者向けページに案内があります（制度ごとの条件は市町村で確認）",
      "📋 start-fukuagri.jp/procedure/ で申請の流れを確認",
    ],
  };
  if (!isHire) steps.push(certStep);

  if (fromTokyo) {
    steps.push({
      icon: "🏠",
      phase: "移住手続き",
      title: "ふくしま移住支援金を申請する",
      description: "転入後に申請できます。転入前に必ず市町村の担当窓口で要件を確認してください。",
      details: [
        "💰 支給額：単身60万円・家族100万円（一時金）",
        "📍 申請先：転入先の市町村担当窓口",
        "🗼 対象：東京23区に住んでいた方、東京圏（東京・埼玉・千葉・神奈川）から23区へ通勤していた方など。直近10年のうち5年以上の条件や、移住先での就業などの条件があります（詳しい要件は県・市町村で確認）",
        "⚠️ 転入後の申請。転入前に要件確認必須",
        "🌐 詳細：福島県公式 ふくしま移住支援金給付事業",
      ],
      warn: "転入前に市町村窓口で要件を確認してください。要件を満たさないと支給されません。",
    });
  }

  return steps;
}
