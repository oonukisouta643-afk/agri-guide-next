import type { SimulatorState } from "@/lib/simulator/types";

// 結果⑨「就農ロードマップ」フェーズ別タイムライン
// 出典：agri-simulator-v4.html（旧版）buildResult()内のロードマップ構築ロジック（545〜627行目）を移植。
// 旧版は回答内容（研修要否・年齢・自己資金・移住元）に応じて3〜5ステップを動的に組み立てていたが、
// Next版では固定4フェーズの静的配列になっていたため、この関数で旧版のロジック・文言を復元する。

export type RoadmapStep = {
  icon: string;
  phase: string;
  title: string;
  description: string;
  details: string[];
  warn?: string;
};

export function buildRoadmap(s: SimulatorState): RoadmapStep[] {
  const steps: RoadmapStep[] = [];

  // 50歳以上は就農準備資金（研修中の生活支援）の対象外
  const trainOk = s.age !== "50p";
  // 農業バイト経験あり／研修経験ありは「経験者」として研修フェーズをスキップ
  const hasExp = s.exp === "part" || s.exp === "train";
  // 東京圏・その他都市部からの移住はふくしま移住支援金の対象
  const fromTokyo = s.loc === "tokyo" || s.loc === "other";

  if (!hasExp) {
    steps.push({
      icon: "🔍",
      phase: "まず最初に（リスクゼロ・無料）",
      title: "ふくのうの「お試し就農体験」に申し込む",
      description:
        "実際の農家で1〜3日間の作業体験ができます。交通費の補助もあります。決断は不要です。まず体で確かめるだけでOK。",
      details: [
        "📞 申し込み先：ふくのう（福島県農業経営・就農支援センター）",
        "🌐 start-fukuagri.jp/trainee/ から募集情報を確認",
        "💰 参加費：無料（交通費補助あり）",
        "📅 期間：1〜3日間（短期から選べる）",
        "✅ 体験後に就農を決める必要はありません",
      ],
    });
  } else {
    steps.push({
      icon: "📋",
      phase: "まず最初に",
      title: "ふくのうに就農相談の予約を入れる",
      description:
        "農業経験がある場合は具体的な就農相談から入るのがスムーズです。認定新規就農者の認定に向けた計画づくりをサポートしてもらえます。",
      details: [
        "📞 相談先：ふくのう（福島県農業経営・就農支援センター）",
        "🌐 start-fukuagri.jp/support/ から予約",
        "💰 相談費用：無料",
        "📋 農業経営改善計画の作成サポートあり",
      ],
    });
  }

  if (trainOk && !hasExp) {
    steps.push({
      icon: "📚",
      phase: "研修フェーズ（年間150万円を受給しながら）",
      title: "農業研修機関に登録して研修を受ける",
      description:
        "就農準備資金（年間150万円）を受け取りながら農業を学べます。研修期間中に農地・農機・販路の目処を立てます。",
      details: [
        "💰 就農準備資金：年間150万円（月12.5万円）を最長2年間受給",
        "📅 研修期間：年間1,200時間以上が条件",
        "🏛️ 登録先：ふくのう経由で研修機関を紹介してもらえます",
        "📋 start-fukuagri.jp/procedure/ で就農ステップ全体を確認",
        "⚠️ 研修機関への登録は就農の1〜2年前が目安",
      ],
      warn: "早く動くほど補助金の受給期間が長くなります。",
    });
  }

  if (s.cap === "u100" || s.cap === "100to300") {
    steps.push({
      icon: "🏦",
      phase: "資金調達",
      title: "日本政策金融公庫に農業融資の相談をする",
      description:
        "自己資金が少なくても農業経営基盤強化資金（スーパーL資金）で低金利融資を受けられます。まず相談だけでもOKです。",
      details: [
        "🏦 相談先：日本政策金融公庫（農業融資窓口）",
        "💰 特例金利0%が適用される場合あり",
        "📋 融資申請には農業経営計画書が必要",
        "✅ 「相談だけ」でも対応してもらえます。まず電話予約から",
      ],
    });
  }

  steps.push({
    icon: "📋",
    phase: "就農開始",
    title: "「認定新規就農者」の認定を取得する",
    description:
      "農業委員会に農業経営改善計画を提出して認定を受けると、経営開始資金（年間150万円×最長3年）を受給できます。すべての補助金の前提条件です。",
    details: [
      "🏛️ 申請先：市町村の農業委員会",
      "💰 認定後：経営開始資金 年間150万円×最長3年間",
      "💰 認定後：地域計画早期実現支援枠 上限600万円（2026年新設）",
      "📒 青色申告の実施が条件（税務署に申請が必要）",
      "📋 start-fukuagri.jp/procedure/ で申請の流れを確認",
    ],
  });

  if (fromTokyo) {
    steps.push({
      icon: "🏠",
      phase: "移住手続き",
      title: "ふくしま移住支援金を申請する",
      description: "転入後に申請できます。転入前に必ず市町村の担当窓口で要件を確認してください。",
      details: [
        "💰 支給額：単身60万円・家族100万円（一時金）",
        "📍 申請先：転入先の市町村担当窓口",
        "🗼 対象：東京圏（東京・神奈川・埼玉・千葉・茨城・栃木・群馬・山梨）からの移住",
        "⚠️ 転入後の申請。転入前に要件確認必須",
        "🌐 詳細：福島県公式 ふくしま移住支援金給付事業",
      ],
      warn: "転入前に市町村窓口で要件を確認してください。要件を満たさないと支給されません。",
    });
  }

  return steps;
}
